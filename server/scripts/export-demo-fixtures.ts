import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { DEMO_CANDIDATES, DEMO_JOB } from '../src/demo/dataset.ts';

// EXPORTS THE DEMO'S SOURCE TO THE TWO PORTFOLIO SITES, AND CHECKS THEY HAVE NOT DRIFTED.
//
//   node scripts/export-demo-fixtures.ts            writes the vendored files and dataset.gen.ts into both sites
//   node scripts/export-demo-fixtures.ts --check    changes nothing; exits 1 if either site's copy is not what this would write
//   --sites=<dir>,<dir>                              the site checkouts (default: ../portfolio and ../sameer-3d-portfolio beside this repository)
//
// Each site holds a copy of eleven of this repository's source files under `src/demo/p3/vendored/`, each behind a header that names its
// source and the SHA-256 of what follows, and a generated `dataset.gen.ts` with the demo job, the five invented CVs and what each one
// is meant to show. The sites' own tests check the headers against the files and (when this repository is beside them) against the
// source here. This script is what writes them, so a change here is one command, not a hand edit that the next sync silently loses.
// `--check` compares everything except the "Source commit" line, which names the commit the files were made from.

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SERVER_SRC = path.resolve(HERE, '../src');
const REPO_ROOT = path.resolve(HERE, '../..');

/** The files the sites copy, relative to `server/src/`. */
export const VENDORED_FILES = [
  'adapters/llm/mock.ts',
  'adapters/llm/types.ts',
  'agent/extractionPrompt.ts',
  'agent/extractionSchema.ts',
  'agent/matchRules.ts',
  'agent/mockExtractor.ts',
  'agent/rankRules.ts',
  'agent/redact.ts',
  'agent/score.ts',
  'agent/verifyEvidence.ts',
  'domain/ats.ts',
] as const;

const VENDORED_HEADER = "/*\n * GENERATED FILE — DO NOT EDIT\n *\n * Copied verbatim from the Explainable ATS. Everything below this header is\n * that project's source, byte for byte. Edit it there, then re-run the\n * generator — an edit made here is silently lost on the next export and\n * makes the demo stop matching the system it claims to demonstrate.\n *\n * Source:\n *   @@SOURCE@@\n *\n * Source commit:\n *   @@COMMIT@@\n *\n * Body SHA-256:\n *   @@HASH@@\n *\n * Generated by:\n *   explainable-ats/server/scripts/export-demo-fixtures.ts\n *\n * Verify with:\n *   node scripts/export-demo-fixtures.ts --check\n */\n";
const DATASET_HEAD = "/*\n * GENERATED FILE — DO NOT EDIT\n *\n * The Explainable ATS demo dataset, emitted as data from that project's own\n * source. No value here was typed by hand.\n *\n * Every person, employer, address, email and phone number is invented. Emails\n * use the .invalid top-level domain and phone numbers come from the range\n * reserved for fiction, both of which are guaranteed never to reach anyone. The\n * personal details exist so a demo can show them being removed before anything\n * reads the CV.\n *\n * Source:\n *   explainable-ats/server/src/demo/dataset.ts\n *\n * Source commit:\n *   @@COMMIT@@\n *\n * Generated by:\n *   explainable-ats/server/scripts/export-demo-fixtures.ts\n *\n * Verify with:\n *   node scripts/export-demo-fixtures.ts --check\n */\n";
const DATASET_TYPES = "import type { RankTier } from './vendored/agent/rankRules.ts'\nimport type { MatchVerdict, RequirementKind, Seniority } from './vendored/domain/ats.ts'\n\n/** One requirement on the demo job, exactly as the project declares it. */\nexport type DemoJobRequirement = {\n  label: string\n  criterion: string\n  kind: RequirementKind\n  weight: number\n}\n\nexport type DemoJob = {\n  title: string\n  seniority: Seniority\n  description: string\n  requirements: readonly DemoJobRequirement[]\n}\n\n/**\n * What a candidate is in the dataset to demonstrate.\n *\n * Carried across so the demo can state what each candidate shows. It is a\n * statement of intent, not a shortcut: the project runs the real pipeline and\n * checks the dataset actually produces these, and the demo runner will be held\n * to the same values.\n */\nexport type DemoExpectation = {\n  tier: RankTier\n  scoreBasisPoints: number | null\n  verdicts: readonly MatchVerdict[]\n  demonstrates: string\n}\n\nexport type DemoCandidate = {\n  reference: string\n  displayName: string\n  /** Plain text. This project has no PDF or DOCX parser. */\n  resume: string\n  /** 'queued' opens an evaluation and stops — the honest 'not assessed yet' state. */\n  assess: 'scored' | 'queued'\n  expected: DemoExpectation\n}\n\n";

const lf = (text: string): string => text.replace(/\r\n/g, '\n');
const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');

function sourceCommit(): string {
  try {
    return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: REPO_ROOT, encoding: 'utf8' }).trim();
  } catch {
    return '0'.repeat(40);
  }
}

/** The whole vendored file as it should be written. */
export function vendoredText(relative: string, commit: string): string {
  const body = lf(fs.readFileSync(path.join(SERVER_SRC, relative), 'utf8'));
  const header = VENDORED_HEADER.replace('@@SOURCE@@', `explainable-ats/server/src/${relative}`).replace('@@COMMIT@@', commit).replace('@@HASH@@', sha256(body));
  return header + body;
}

/** The generated dataset file as it should be written. */
export function datasetText(commit: string): string {
  const candidates = DEMO_CANDIDATES.map((candidate) => ({
    reference: candidate.reference,
    displayName: candidate.displayName,
    assess: candidate.assess,
    resume: candidate.resume,
    expected: {
      tier: candidate.expected.tier,
      scoreBasisPoints: candidate.expected.scoreBasisPoints,
      verdicts: candidate.expected.verdicts,
      demonstrates: candidate.expected.demonstrates,
    },
  }));
  return (
    DATASET_HEAD.replace('@@COMMIT@@', commit) +
    DATASET_TYPES +
    `export const DEMO_JOB: DemoJob = ${JSON.stringify(DEMO_JOB, null, 2)}\n\n` +
    `export const DEMO_CANDIDATES: readonly DemoCandidate[] = ${JSON.stringify(candidates, null, 2)}\n`
  );
}

const withoutCommit = (text: string): string => lf(text).replace(/(Source commit:\s*\n\s*\*\s*)[0-9a-f]{40}/, '$1<commit>');

function main(): number {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const sitesArg = args.find((value) => value.startsWith('--sites='))?.slice('--sites='.length);
  const sites = sitesArg ? sitesArg.split(',').map((dir) => path.resolve(dir)) : [path.resolve(REPO_ROOT, '../portfolio'), path.resolve(REPO_ROOT, '../sameer-3d-portfolio')];
  const commit = sourceCommit();

  let problems = 0;
  for (const site of sites) {
    const p3 = path.join(site, 'src', 'demo', 'p3');
    if (!fs.existsSync(p3)) {
      console.log(`MISSING: ${p3} (is the site checked out?)`);
      problems += 1;
      continue;
    }
    const wanted: Array<[string, string]> = [
      ...VENDORED_FILES.map((relative): [string, string] => [path.join(p3, 'vendored', relative), vendoredText(relative, commit)]),
      [path.join(p3, 'dataset.gen.ts'), datasetText(commit)],
    ];
    for (const [file, text] of wanted) {
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      const same = current !== null && withoutCommit(current) === withoutCommit(text);
      if (check) {
        if (!same) {
          console.log(`DRIFTED: ${path.relative(REPO_ROOT, file)}`);
          problems += 1;
        }
      } else if (!same) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, text);
        console.log(`wrote ${path.relative(REPO_ROOT, file)}`);
      }
    }
  }
  if (check) console.log(problems === 0 ? `OK: ${sites.length} site(s) match this repository.` : `${problems} file(s) differ. Run without --check to write them.`);
  else console.log(problems === 0 ? 'Done.' : `${problems} problem(s).`);
  return problems === 0 ? 0 : 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
